function applyI18n(lang) {
  const dict = i18n[lang] || i18n.es;
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const k = el.getAttribute('data-i18n');
    if (k && dict[k] !== undefined) el.textContent = dict[k];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const k = el.getAttribute('data-i18n-placeholder');
    if (k && dict[k] !== undefined) el.setAttribute('placeholder', dict[k]);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const k = el.getAttribute('data-i18n-aria-label');
    if (k && dict[k] !== undefined) el.setAttribute('aria-label', dict[k]);
  });
}

function setLang(lang) {
  localStorage.setItem('lang', lang);
  applyI18n(lang);
  const btn = document.getElementById('langToggle');
  if (btn) btn.textContent = lang === 'es' ? 'EN' : 'ES';
}

const savedLang = localStorage.getItem('lang') || 'es';
setLang(savedLang);
const yearEl = document.getElementById('year');
if (yearEl) yearEl.textContent = new Date().getFullYear();

const internalLinks = document.querySelectorAll('a[href^="#"]');
internalLinks.forEach((a) => {
  a.addEventListener('click', (e) => {
    const href = a.getAttribute('href');
    if (!href || href === '#' || href.length < 2) return;
    const target = document.querySelector(href);
    if (target) {
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  });
});

const toTop = document.getElementById('toTop');
if (toTop) {
  toTop.addEventListener('click', (e) => {
    e.preventDefault();
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
}

const form = document.getElementById('quoteForm');
const formMsg = document.getElementById('formMsg');

function showMsg(text, type = 'info') {
  if (!formMsg) return;
  formMsg.textContent = text;
  formMsg.style.color = type === 'error' ? '#b91c1c' : type === 'success' ? '#065f46' : '#334155';
}

if (form) {
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const data = new FormData(form);

    const nombre = (data.get('nombre') || '').toString().trim();
    const telefono = (data.get('telefono') || '').toString().trim();
    const email = (data.get('email') || '').toString().trim();
    const tipo = (data.get('tipo') || '').toString().trim();

    if (!nombre || !telefono || !email || !tipo) {
      showMsg(i18n[localStorage.getItem('lang') || 'es'].form_required, 'error');
      return;
    }

    const emailOk = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
    if (!emailOk) {
      showMsg(i18n[localStorage.getItem('lang') || 'es'].form_email_invalid, 'error');
      return;
    }

    showMsg(i18n[localStorage.getItem('lang') || 'es'].form_success, 'success');
    form.reset();
  });
}

const header = document.querySelector('.site-header');
if (header) {
  const onScroll = () => {
    const scrolled = window.scrollY > 8;
    header.style.boxShadow = scrolled ? '0 6px 20px rgba(2,8,23,0.06)' : 'none';
  };
  window.addEventListener('scroll', onScroll);
  onScroll();
}

const langToggle = document.getElementById('langToggle');
if (langToggle) {
  langToggle.addEventListener('click', () => {
    const current = localStorage.getItem('lang') || 'es';
    const next = current === 'es' ? 'en' : 'es';
    setLang(next);
  });
}
